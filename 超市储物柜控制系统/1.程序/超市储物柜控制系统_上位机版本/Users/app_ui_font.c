static const uint8_t *AppFont_FindGlyph(uint16_t code)
{
    uint16_t i;

    for (i = 0U; i < (uint16_t)(sizeof(s_glyphs) / sizeof(s_glyphs[0])); i++)
    {
        if (s_glyphs[i].code == code)
        {
            return s_glyphs[i].data;
        }
    }

    return NULL;
}

static uint16_t AppFont_DecodeUtf8(const char **text)
{
    const uint8_t *p = (const uint8_t *)(*text);
    uint16_t code = 0U;

    if (p[0] < 0x80U)
    {
        code = p[0];
        *text += 1;
    }
    else if ((p[0] & 0xE0U) == 0xC0U)
    {
        code = (uint16_t)(((p[0] & 0x1FU) << 6U) | (p[1] & 0x3FU));
        *text += 2;
    }
    else if ((p[0] & 0xF0U) == 0xE0U)
    {
        code = (uint16_t)(((p[0] & 0x0FU) << 12U) | ((p[1] & 0x3FU) << 6U) | (p[2] & 0x3FU));
        *text += 3;
    }
    else
    {
        code = '?';
        *text += 1;
    }

    return code;
}

void AppFont_DrawText(uint16_t x, uint16_t y, const char *utf8, uint16_t color, uint16_t bgColor)
{
    const char *p = utf8;

    if (p == NULL)
    {
        return;
    }

    while (*p != '\0')
    {
        uint16_t code = AppFont_DecodeUtf8(&p);
        const uint8_t *glyph;

        if (code == '\n')
        {
            x = 0U;
            y = (uint16_t)(y + 16U);
            continue;
        }

        if (code < 0x80U)
        {
            ST7735_DrawChar(x, y + 3U, (char)code, color, bgColor, &Font_7x10);
            x = (uint16_t)(x + Font_7x10.width);
        }
        else
        {
            glyph = AppFont_FindGlyph(code);
            if (glyph != NULL)
            {
                ST7735_DrawGlyph16(x, y, glyph, color, bgColor);
            }
            else
            {
                ST7735_DrawChar(x, y + 3U, '?', color, bgColor, &Font_7x10);
            }
            x = (uint16_t)(x + 16U);
        }

        if (x >= 128U)
        {
            x = 0U;
            y = (uint16_t)(y + 16U);
        }
    }
}

uint16_t AppFont_TextWidth(const char *utf8)
{
    const char *p = utf8;
    uint16_t width = 0U;

    if (p == NULL)
    {
        return 0U;
    }

    while (*p != '\0')
    {
        uint16_t code = AppFont_DecodeUtf8(&p);
        width = (uint16_t)(width + ((code < 0x80U) ? Font_7x10.width : 16U));
    }

    return width;
}
